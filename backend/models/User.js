import mongoose from "mongoose";

const userSchema = new mongoose.Schema({
    name: {
        type: String,
        required: true
    },
    email: {
        type: String,
        required: true,
        unique: true,
        lowercase: true
    },
    password: {
        type: String,
        required: true // this will store the HASHED password, never plain text
    }
}, { timestamps: true });

export default mongoose.model("User", userSchema);